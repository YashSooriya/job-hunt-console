import assert from "node:assert/strict";
import { readFile, stat } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.dirname(fileURLToPath(import.meta.url));
const read = (relative) => readFile(path.join(root, relative), "utf8");
const packageManifest = JSON.parse(await read("package.json"));
const releaseVersion = packageManifest.version;
assert.match(releaseVersion, /^\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?$/, "The extension package must declare a semantic release version.");
const manifest = JSON.parse(await read("dist/manifest.json").catch(() => "{}"));
assert.equal(manifest.manifest_version, 3, "The built extension must be Manifest V3.");
assert.equal(manifest.version, releaseVersion, "The built manifest version must come from the extension package version.");
assert.deepEqual(manifest.permissions?.slice().sort(), ["alarms", "downloads", "scripting", "storage", "tabs"], "The extension permissions must stay limited to bridge delivery and JSON artifact download.");
assert.ok(!manifest.host_permissions?.includes("<all_urls>"), "The extension must not request all-sites access.");
assert.deepEqual(manifest.host_permissions?.filter((value) => value.includes("chatgpt") || value.includes("openai")), ["https://chatgpt.com/*", "https://chat.openai.com/*"], "Only the supported ChatGPT origins may be granted.");
assert.equal(manifest.background?.service_worker, "background.js");
for (const file of ["background.js", "chatgpt.js", "jobhunt-bridge.js", "popup.js", "options.js", "popup.html", "options.html", "styles.css"]) await read(`dist/${file}`);
assert.ok(!(await read("dist/popup.html")).includes("Enable Automatic Send"), "The extension must not expose an Automatic Send checkbox.");
assert.equal((await read("manifest.template.json")).match(/\"version\":\s*\"([^\"]+)\"/)?.[1], "__JOB_HUNT_EXTENSION_VERSION__", "The manifest template must use the package version placeholder.");
const optionsHtml = await read("dist/options.html");
assert.ok(optionsHtml.includes(`Extension version <span id="version">${releaseVersion}</span>`), "The built options page must display the package version.");
assert.ok(!optionsHtml.includes("__JOB_HUNT_EXTENSION_VERSION__"), "The built options page must not contain an unresolved version placeholder.");

const source = await Promise.all(["src/background.ts", "src/content/chatgpt.ts", "src/content/jobhunt-bridge.ts", "src/content/ui-adapter.ts", "src/shared/backend-client.ts", "src/shared/protocol.ts", "src/shared/runtime-messaging.ts"].map(read));
const combined = source.join("\n");
const backgroundSource = source[0];
const chatgptBundle = await read("dist/chatgpt.js");
const jobhuntBundle = await read("dist/jobhunt-bridge.js");
const backgroundBundle = await read("dist/background.js");
const popupBundle = await read("dist/popup.js");
const buildIds = [chatgptBundle, jobhuntBundle, backgroundBundle, popupBundle].map((bundle) => bundle.match(/(?:var|let|const) EXTENSION_BUILD_ID = true \? "([^"]+)"/)?.[1] || null);
assert.ok(buildIds.every(Boolean), "Every browser bundle must contain a build identity.");
assert.equal(new Set(buildIds).size, 1, "All browser bundles must share one build identity.");
assert.ok(buildIds[0].startsWith(`${releaseVersion}-`), "The build identity must be namespaced by the package version.");
assert.ok(backgroundBundle.includes(releaseVersion), "The background bundle must contain the package version at build time.");
assert.ok(popupBundle.includes("Extension version:"), "The popup must display the runtime extension version.");
assert.ok(popupBundle.includes("Extension build:"), "The popup must display the runtime extension build id.");
assert.ok(![chatgptBundle, jobhuntBundle, backgroundBundle].some((bundle) => bundle.includes("__JOB_HUNT_BRIDGE_BUILD_ID__")), "The build-time identity placeholder must not ship in browser bundles.");
const archivePath = path.join(root, `dist/jobhunt-chatgpt-bridge-v${releaseVersion}.zip`);
assert.ok((await stat(archivePath)).size > 0, "The versioned extension archive must exist and be non-empty.");
for (const forbidden of ["OPENAI_API_KEY", "api.openai.com", "webRequest", "debugger", "chrome.cookies", "<all_urls>"]) assert.ok(!combined.includes(forbidden), `Bridge source contains forbidden capability: ${forbidden}`);
assert.match(combined, /EXECUTE_DISPATCH/);
assert.match(combined, /START_DISPATCH/);
assert.match(combined, /jobhunt-start-dispatch-v1/);
assert.match(combined, /GET_DISPATCH_DELIVERY/);
assert.match(combined, /DISPATCH_RESULT_READY/);
assert.match(combined, /publishDispatchResult/);
assert.match(combined, /delivery_signal_wait_ms/);
assert.match(combined, /deliveryPending/);
assert.match(combined, /delivery_uncertain/);
assert.match(combined, /boundConversationUrl/);
assert.match(combined, /SET_UP_WORKFLOW_CONVERSATIONS/);
assert.match(combined, /CREATE_WORKFLOW_CONVERSATION/);
assert.match(combined, /RECOVER_WORKFLOW_CONVERSATION/);
assert.match(combined, /VERIFY_BOUND_CONVERSATION/);
assert.match(combined, /conversation_missing/);
assert.match(combined, /waitForTabNavigation/);
assert.match(combined, /ROTATE_WORKFLOW_CONVERSATION/);
assert.match(combined, /JOBHUNT_BRIDGE_RESET_LOCAL/);
assert.match(combined, /RESET_LOCAL_PAIRING/);
assert.match(combined, /CHECK_EXISTING_DISPATCH_RESPONSE/);
assert.match(combined, /get_active_dispatch/);
assert.match(combined, /responseWaitInFlight/);
assert.match(combined, /workflow-setup-resume/);
assert.match(combined, /withChatGptUiOperation/);
assert.match(combined, /boundProjectUrl/);
assert.match(combined, /tabs\.onUpdated/);
assert.match(combined, /MutationObserver/);
assert.match(backgroundSource, /function startWorkflowSetup/);
assert.match(backgroundSource, /SET_UP_WORKFLOW_CONVERSATIONS\"\) return startWorkflowSetup\(\);/);
assert.match(backgroundSource, /conversationSlots\.some\(\(slot\) => slot\.projectVerified === true\)/);
assert.match(backgroundSource, /return pingContent\(tabId, 30000, expectedUrl, currentScriptInjectionAttempted\);/);
assert.match(backgroundSource, /GET_DISPATCH_DELIVERY_VERSIONED/);
assert.match(combined, /GET_DISPATCH_DELIVERY_VERSIONED/);
assert.match(combined, /JOBHUNT_PAGE_PORT_NAME = "jobhunt-page-bridge-v1"/);
assert.match(backgroundSource, /LEGACY_JOBHUNT_PAGE_PORT_NAME_PATTERN/);
assert.match(backgroundSource, /isJobHuntPagePortName\(port\.name\)/);
assert.match(backgroundSource, /ACTIVE_RESPONSE_RECOVERY_TIMEOUT_MS/);
assert.match(backgroundSource, /response_capture_timeout/);
assert.ok(!backgroundSource.includes("chrome.windows.create"), "Automatic dispatch must not create a helper window that can steal focus.");
assert.match(backgroundSource, /tabs\.create\(\{ windowId, url: boundUrl, active: false \}\)/);
assert.match(backgroundSource, /sourceWindowIdFromSender/);
assert.match(backgroundSource, /focusPreserved/);
assert.match(combined, /EXTENSION_BUILD_ID/);
assert.match(combined, /contentInstanceId/);
assert.match(combined, /probeRuntime/);
assert.match(combined, /dispose\(\)/);
assert.match(combined, /removeListener/);
assert.match(combined, /createRuntimeMessageHelper/);
assert.match(combined, /runtimeMessageFailureKind/);
assert.match(combined, /runtimeRetryDelayMs/);
assert.match(combined, /context_invalidated/);
assert.match(combined, /worker_unavailable/);
assert.match(combined, /PAGE_PORT_RECONNECT_MAX_ATTEMPTS/);
assert.match(combined, /MAX_PENDING_PAGE_HINTS/);
assert.match(combined, /MARK_DISPATCH_SEND_ATTEMPTED/);
console.log("ChatGPT bridge extension verification passed.");
