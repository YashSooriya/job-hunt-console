import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.dirname(fileURLToPath(import.meta.url));
const read = (relative) => readFile(path.join(root, relative), "utf8");
const manifest = JSON.parse(await read("dist/manifest.json").catch(() => "{}"));
assert.equal(manifest.manifest_version, 3, "The built extension must be Manifest V3.");
assert.deepEqual(manifest.permissions?.slice().sort(), ["alarms", "downloads", "scripting", "storage", "tabs"], "The extension permissions must stay limited to bridge delivery and JSON artifact download.");
assert.ok(!manifest.host_permissions?.includes("<all_urls>"), "The extension must not request all-sites access.");
assert.deepEqual(manifest.host_permissions?.filter((value) => value.includes("chatgpt") || value.includes("openai")), ["https://chatgpt.com/*", "https://chat.openai.com/*"], "Only the supported ChatGPT origins may be granted.");
assert.equal(manifest.background?.service_worker, "background.js");
for (const file of ["background.js", "chatgpt.js", "jobhunt-bridge.js", "popup.js", "options.js", "popup.html", "options.html", "styles.css"]) await read(`dist/${file}`);
assert.ok(!(await read("dist/popup.html")).includes("Enable Automatic Send"), "The extension must not expose an Automatic Send checkbox.");

const source = await Promise.all(["src/background.ts", "src/content/chatgpt.ts", "src/content/jobhunt-bridge.ts", "src/content/ui-adapter.ts", "src/shared/backend-client.ts", "src/shared/protocol.ts"].map(read));
const combined = source.join("\n");
const backgroundSource = source[0];
for (const forbidden of ["OPENAI_API_KEY", "api.openai.com", "webRequest", "debugger", "chrome.cookies", "<all_urls>"]) assert.ok(!combined.includes(forbidden), `Bridge source contains forbidden capability: ${forbidden}`);
assert.match(combined, /EXECUTE_DISPATCH/);
assert.match(combined, /START_DISPATCH/);
assert.match(combined, /jobhunt-start-dispatch-v1/);
assert.match(combined, /GET_DISPATCH_DELIVERY/);
assert.match(combined, /DISPATCH_RESULT_READY/);
assert.match(combined, /publishDispatchResult/);
assert.match(combined, /delivery_signal_wait_ms/);
assert.match(combined, /deliveryPending/);
assert.match(combined, /delivery_uncertain/);
assert.match(combined, /boundConversationUrl/);
assert.match(combined, /SET_UP_WORKFLOW_CONVERSATIONS/);
assert.match(combined, /CREATE_WORKFLOW_CONVERSATION/);
assert.match(combined, /RECOVER_WORKFLOW_CONVERSATION/);
assert.match(combined, /VERIFY_BOUND_CONVERSATION/);
assert.match(combined, /conversation_missing/);
assert.match(combined, /waitForTabNavigation/);
assert.match(combined, /ROTATE_WORKFLOW_CONVERSATION/);
assert.match(combined, /JOBHUNT_BRIDGE_RESET_LOCAL/);
assert.match(combined, /RESET_LOCAL_PAIRING/);
assert.match(combined, /CHECK_EXISTING_DISPATCH_RESPONSE/);
assert.match(combined, /get_active_dispatch/);
assert.match(combined, /responseWaitInFlight/);
assert.match(combined, /workflow-setup-resume/);
assert.match(combined, /withChatGptUiOperation/);
assert.match(combined, /boundProjectUrl/);
assert.match(combined, /tabs\.onUpdated/);
assert.match(combined, /MutationObserver/);
assert.match(backgroundSource, /function startWorkflowSetup/);
assert.match(backgroundSource, /SET_UP_WORKFLOW_CONVERSATIONS\"\) return startWorkflowSetup\(\);/);
assert.match(backgroundSource, /conversationSlots\.some\(\(slot\) => slot\.projectVerified === true\)/);
assert.match(backgroundSource, /return pingContent\(tabId, 30000, expectedUrl, currentScriptInjectionAttempted\);/);
assert.match(backgroundSource, /GET_DISPATCH_DELIVERY_VERSIONED/);
assert.match(combined, /GET_DISPATCH_DELIVERY_VERSIONED/);
assert.match(combined, /JOBHUNT_PAGE_PORT_NAME = "jobhunt-page-bridge-v1"/);
assert.match(backgroundSource, /LEGACY_JOBHUNT_PAGE_PORT_NAME_PATTERN/);
assert.match(backgroundSource, /isJobHuntPagePortName\(port\.name\)/);
assert.match(backgroundSource, /ACTIVE_RESPONSE_RECOVERY_TIMEOUT_MS/);
assert.match(backgroundSource, /response_capture_timeout/);
console.log("ChatGPT bridge extension verification passed.");
